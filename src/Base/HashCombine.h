#ifndef BASE_HASHCOMBINE_H
#define BASE_HASHCOMBINE_H

// hash_combine on its own, out of Base/Tools.h (which brings Qt, Console.h and
// Exception.h along), for headers that only hash a key. Tools.h includes it.

#include <functional>

namespace Base
{

// copied from boost::hash_combine. 
template <class S, class T>
inline void hash_combine(S& seed, const T& v)
{
    std::hash<T> hasher;
    seed ^= hasher(v) + 0x9e3779b9 + (seed<<6) + (seed>>2);
}

}  // namespace Base

#endif  // BASE_HASHCOMBINE_H
